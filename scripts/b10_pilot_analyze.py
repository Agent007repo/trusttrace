"""B10 pilot analysis and paper inputs. Writes 'pending' outputs until every input exists.

Inputs (all committed once available):
  data/b10_pilot/gold.jsonl                     human labels, frozen when Samarth locked them
  results/b10-pilot/raw/runs.jsonl              sealed model generations
  results/b10-pilot/raw/cosine_cache.json       cached statement similarities
  results/b10-pilot/audit/decisions.jsonl       Samarth's blinded audit decisions
Outputs:
  results/derived/b10_pilot_summary.json, results/derived/b10_pilot_rows.jsonl
  results/b10-pilot/audit/packet.jsonl          blinded audit items (no algorithm decision)
  paper/generated/*.tex
"""

import datetime
import json
import math
from pathlib import Path

from trusttrace.b10 import Annotation
from trusttrace.b10_pilot import audit_sample, cohen_kappa, match_run, register_sources, summarize
from trusttrace.experiment_analysis import ExtractionRun

root = Path(__file__).resolve().parents[1]
cfg = json.loads((root / "configs/b10_pilot.json").read_text())
SEP = "␟"
gen = root / "paper/generated"
gen.mkdir(parents=True, exist_ok=True)
derived = root / "results/derived"
derived.mkdir(parents=True, exist_ok=True)
paths = {
    "gold": root / "data/b10_pilot/gold.jsonl",
    "runs": root / "results/b10-pilot/raw/runs.jsonl",
    "cache": root / "results/b10-pilot/raw/cosine_cache.json",
    "audit": root / "results/b10-pilot/audit/decisions.jsonl",
}
packet_path = root / "results/b10-pilot/audit/packet.jsonl"
key_path = root / "results/b10-pilot/audit/sample_key.jsonl"


def tex_escape(s: str) -> str:
    return s.replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def write(name: str, text: str) -> None:
    (gen / name).write_text(text.strip() + "\n")


# --- traceability numbers (RQ1) -------------------------------------------------
trace = json.loads((derived / "traceability.json").read_text())
covered = trace["must_denominator"] * trace["must_coverage"] + trace["should_covered"]
write(
    "trace_results.tex",
    f"""The traceability tool validates the case with {len(trace["errors"])} link errors and {len(trace["orphans"])} orphaned decisions, components, tests or conflicts. Of {trace["total_requirements"]} requirements, {int(covered)} are covered by a decision, a component, a six-part scenario and a passing requirement-tagged test: all {trace["must_denominator"]} must requirements and {trace["should_covered"]} of {trace["should_denominator"]} should requirements. The two uncovered requirements ({", ".join(trace["uncovered"])}) need verified regulatory sources, which could not be retrieved. These numbers come from an executed test run and are regenerated by \\texttt{{make analyze}}.""",
)
write("report_date.tex", "October 2026")

# --- trust relationships in the case (generated from the authored model) ---------
import collections  # noqa: E402

import yaml  # noqa: E402

case = yaml.safe_load((root / "data/synthetic_case.yaml").read_text())
holder = {x["id"]: x["stakeholder_id"] for x in case["trustors"] + case["trustees"]}
pairs = collections.Counter(
    (holder[r["trustor"]], holder[r["trustee"]]) for r in case["requirements"]
)
platform_share = sum(n for (_, te), n in pairs.items() if te == "platform")
rel_lines = [
    r"\begin{table}[t]\centering\small",
    r"\caption{Trust relationships in the case: requirements per trustor and trustee (generated from the case model).}\label{tab:relations}",
    r"\begin{tabular}{@{}llr@{}}\toprule Trustor & Trustee & Requirements\\\midrule",
]
for (tr, te), n in sorted(pairs.items(), key=lambda kv: (-kv[1], kv[0])):
    rel_lines.append(f"{tr} & {te} & {n}\\\\")
rel_lines.append(r"\bottomrule\end{tabular}\end{table}")
write("trust_relations.tex", "\n".join(rel_lines))
write(
    "trust_relations_text.tex",
    f"The platform operator is the trustee in {platform_share} of {len(case['requirements'])} requirements "
    f"across {len(pairs)} distinct trustor and trustee pairs (Table~\\ref{{tab:relations}}).",
)

missing = [k for k, p in paths.items() if not p.is_file()]
pending_state = {"status": "pending", "missing_inputs": missing}

if {"gold", "runs", "cache"} & set(missing):
    (derived / "b10_pilot_summary.json").write_text(json.dumps(pending_state, indent=2) + "\n")
    write(
        "b10_results.tex",
        r"""\textbf{Results.} Pending. Generations are sealed until the human labels are locked; no pilot result is reported in this build.
\begin{table}[t]\centering\small\caption{B10 pilot results (pending).}\label{tab:b10}\begin{tabular}{l}\toprule Pending\\\bottomrule\end{tabular}\end{table}""",
    )
    write("abstract_results.tex", "Pilot results are pending in this build.")
    write("b10_pertext.tex", "")
    write("b10_errors.tex", "")
    raise SystemExit(0)

gold_rows = [Annotation.model_validate_json(x) for x in paths["gold"].read_text().splitlines() if x]
gold = {g.source_id: g for g in gold_rows}
runs = [ExtractionRun.model_validate_json(x) for x in paths["runs"].read_text().splitlines() if x]
cache = json.loads(paths["cache"].read_text())["cosine"]
sources = {
    json.loads(x)["id"]: json.loads(x)["text"]
    for x in (root / cfg["sources"]["path"]).read_text().splitlines()
    if x
}
register_sources(sources)
if set(gold) != set(cfg["sources"]["ids"]):
    raise SystemExit("Gold labels must cover exactly the ten pilot texts")


def cosine(a: str, b: str) -> float:
    return float(cache[f"{a}{SEP}{b}"])


weights = (0.6, 0.4)
threshold = float(cfg["matching"]["threshold"])
rows = [match_run(r, gold[r.source_id], cosine, weights, threshold) for r in runs]
with (derived / "b10_pilot_rows.jsonl").open("w") as fh:
    for row in rows:
        fh.write(json.dumps(row) + "\n")
summary = summarize(rows)

# Blinded audit packet: the human sees text, the two requirements, nothing else.
sample = audit_sample(rows, int(cfg["matching"]["human_audit"]["sample_size"]), 20261013)
run_by_id = {r.run_id: r for r in runs}
packet_path.parent.mkdir(parents=True, exist_ok=True)
with packet_path.open("w") as pf, key_path.open("w") as kf:
    for item in sample:
        run = run_by_id[item["run_id"]]
        pred = run.prediction[item["pred"]]
        g = gold[run.source_id].requirements[item["gold"]]
        pf.write(
            json.dumps(
                {
                    "audit_id": item["audit_id"],
                    "source_id": run.source_id,
                    "text": sources[run.source_id],
                    "a": {"statement": pred.statement, "evidence": pred.evidence_span},
                    "b": {"statement": g.statement, "evidence": g.evidence_span},
                }
            )
            + "\n"
        )
        kf.write(json.dumps(item) + "\n")

labelling_minutes = None
stamps = sorted(datetime.datetime.fromisoformat(g.timestamp) for g in gold_rows)
if len(stamps) > 1:
    labelling_minutes = round((stamps[-1] - stamps[0]).total_seconds() / 60, 1)
summary["labelling_span_minutes"] = labelling_minutes
summary["gold_requirements"] = sum(len(g.requirements) for g in gold_rows)

agreement = None
if paths["audit"].is_file():
    human = {
        json.loads(x)["audit_id"]: bool(json.loads(x)["same_obligation"])
        for x in paths["audit"].read_text().splitlines()
        if x
    }
    if set(human) != {s["audit_id"] for s in sample}:
        raise SystemExit("Audit decisions must cover exactly the sampled items")
    agreement = cohen_kappa(
        [human[s["audit_id"]] for s in sample], [bool(s["algorithm_match"]) for s in sample]
    )
    agreement["matcher_precision_on_accepted"] = sum(
        human[s["audit_id"]] for s in sample if s["algorithm_match"]
    ) / max(1, sum(s["algorithm_match"] for s in sample))
    agreement["missed_matches_among_rejected"] = sum(
        human[s["audit_id"]] for s in sample if not s["algorithm_match"]
    ) / max(1, sum(not s["algorithm_match"] for s in sample))
summary["audit"] = agreement
summary["status"] = "complete" if agreement else "awaiting-audit"
reliable = bool(agreement and agreement["cohen_kappa"] >= 0.6)
summary["f1_reliable_by_preregistered_rule"] = reliable if agreement else None
(derived / "b10_pilot_summary.json").write_text(json.dumps(summary, indent=2) + "\n")

# --- paper inputs ----------------------------------------------------------------
short = {
    "Qwen/Qwen2.5-1.5B-Instruct": "Qwen2.5-1.5B",
    "mistralai/Mistral-7B-Instruct-v0.3": "Mistral-7B",
}


def f(x: float | None, d: int = 2) -> str:
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{d}f}"


lines = [
    r"\begin{table}[t]\centering\small",
    r"\caption{B10 pilot by model and condition (10 texts, 3 seeds each). F1 is requirement-level, averaged within text then across texts.}\label{tab:b10}",
    r"\begin{tabular}{@{}llrrrrr@{}}\toprule",
    r"Model & Arm & Valid & Macro F1 & Prec. & Rec. & Exact ev.\\\midrule",
]
for model, m in summary["models"].items():
    for arm in ("naive", "guided"):
        a = m["arms"][arm]
        lines.append(
            f"{short.get(model, model)} & {arm} & {f(a['valid_json_rate'])} & {f(a['macro_f1'])} & "
            f"{f(a['mean_precision'])} & {f(a['mean_recall'])} & {f(a['evidence_exact_rate'])}\\\\"
        )
lines += [r"\bottomrule\end{tabular}\end{table}"]
contrast_txt = []
for model, m in summary["models"].items():
    c = m["guided_minus_naive"]
    contrast_txt.append(
        f"{short.get(model, model)}: {c['mean_difference']:+.3f} [{c['ci_lower']:+.3f}, {c['ci_upper']:+.3f}], "
        f"guided better on {c['texts_guided_better']} of {c['paired_texts']} texts"
    )
lat = {
    short.get(model, model): f"{m['arms']['guided']['latency_median_s']:.0f}"
    for model, m in summary["models"].items()
}
if agreement:
    agree_txt = (
        f"On the 30 audited pairs the matcher agreed with the author's blinded judgement on "
        f"{agreement['percent_agreement'] * 100:.0f}\\% of items (Cohen's $\\kappa={agreement['cohen_kappa']:.2f}$). "
        f"{agreement['matcher_precision_on_accepted'] * 100:.0f}\\% of the pairs it accepted were judged the same obligation, "
        f"and {agreement['missed_matches_among_rejected'] * 100:.0f}\\% of the near-misses it rejected were judged the same obligation. "
        + (
            "By the pre-registered rule ($\\kappa\\geq0.6$), F1 values are treated as reliable for this pilot."
            if reliable
            else "By the pre-registered rule ($\\kappa<0.6$), F1 values are treated as unreliable and we make no directional statement about guidance."
        )
    )
else:
    agree_txt = "The blinded matcher audit is pending in this build, so F1 values are provisional."
body = (
    r"\textbf{Results.} "
    + f"The author labelled {summary['gold_requirements']} atomic obligations across the ten texts"
    + (
        f"; the first and last saves were {labelling_minutes:.0f} minutes apart. "
        if labelling_minutes
        else ". "
    )
    + "Table~\\ref{tab:b10} gives per-arm results. "
    + "The guided minus naive difference in macro F1, with 95\\% bootstrap intervals over texts, was "
    + "; ".join(contrast_txt)
    + ". "
    + agree_txt
    + " Median generation time for the guided arm on two CPU cores was "
    + ", ".join(f"{k} {v}\\,s" for k, v in lat.items())
    + "."
)
write("b10_results.tex", "\n".join(lines) + "\n\n" + body)
best = summary["models"]
write(
    "abstract_results.tex",
    "In a ten-text pilot with two small local models, "
    + "; ".join(
        f"{short.get(mo, mo)} reached macro F1 {f(m['arms']['naive']['macro_f1'])} (naive) and {f(m['arms']['guided']['macro_f1'])} (guided)"
        for mo, m in best.items()
    )
    + (
        f", and the automatic matcher agreed with blinded human judgement at $\\kappa={agreement['cohen_kappa']:.2f}$."
        if agreement
        else "."
    ),
)
print(json.dumps({k: summary[k] for k in ("status", "audit", "labelling_span_minutes")}, indent=1))
