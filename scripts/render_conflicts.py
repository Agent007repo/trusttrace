"""Render the conflict matrix and softgoal graph from data/synthetic_case.yaml."""

from pathlib import Path

import yaml

root = Path(__file__).resolve().parents[1]
case = yaml.safe_load((root / "data/synthetic_case.yaml").read_text())
reqs = {r["id"]: r for r in case["requirements"]}

# Softgoal contributions per decision: (softgoal, effect). Authored analysis, not measured.
CONTRIB = {
    "ADR-001": [("Confidentiality", "+"), ("Information sharing", "-")],
    "ADR-002": [("Human control", "+"), ("Automation efficiency", "-")],
    "ADR-003": [("Transparency", "+"), ("Automation efficiency", "-")],
    "ADR-004": [("Accountability", "+")],
    "ADR-005": [("Reliability", "+")],
    "ADR-006": [("Confidentiality", "+"), ("Information sharing", "-"), ("Accountability", "+")],
    "ADR-007": [("Transparency", "+"), ("Confidentiality", "+")],
    "ADR-008": [("Privacy", "+"), ("Accountability", "-")],
    "ADR-009": [("Accountability", "+"), ("Throughput", "-")],
    "ADR-010": [("Replaceability", "+"), ("Stability", "+"), ("Throughput", "-")],
    "ADR-011": [("Sovereignty", "+"), ("Capability", "-")],
    "ADR-012": [("Security", "+"), ("Capability", "-")],
    "ADR-013": [("Transparency", "+"), ("Throughput", "-")],
    "ADR-014": [("Reliability", "+")],
    "ADR-015": [("Accountability", "+"), ("Reliability", "+")],
}
TITLES = {
    d["id"]: (root / d["document"]).read_text().splitlines()[0].split(": ", 1)[1]
    for d in case["decisions"]
}

lines = [
    "# Conflicts and trade-offs",
    "",
    "Generated by `scripts/render_conflicts.py` from `data/synthetic_case.yaml`. "
    "The conflicts are authored analysis of a synthetic case, not findings from practitioners.",
    "",
    "## Conflict matrix",
    "",
    "| Conflict | Tension | Requirements | Resolved by | Residual cost (from the decision record) |",
    "|---|---|---|---|---|",
]
for c in case["conflicts"]:
    adr = c["resolution_decision"]
    doc = (root / f"docs/adr/adr-{adr.split('-')[1]}.md").read_text()
    cost = (
        doc.split("## Consequences", 1)[1].split("##", 1)[0].strip().split(". ")[0].rstrip(".")
        + "."
    )
    req_list = ", ".join(c["requirements"])
    lines.append(
        f"| {c['id']} | {c['description']} | {req_list} | [{adr}](adr/adr-{adr.split('-')[1]}.md) | {cost} |"
    )

lines += [
    "",
    "## Softgoal contribution graph",
    "",
    "Decisions (boxes) help (+) or hurt (-) quality softgoals (rounded). This follows the spirit of "
    "softgoal interdependency graphs in the NFR framework (Chung et al., 2000). Contributions are our "
    "qualitative judgement and are open to challenge in the practitioner study.",
    "",
    "```mermaid",
    "flowchart LR",
]
goals = sorted({g for v in CONTRIB.values() for g, _ in v})
for g in goals:
    lines.append(f"  {g.replace(' ', '_')}([{g}])")
for adr, effects in CONTRIB.items():
    lines.append(f'  {adr.replace("-", "_")}["{adr}"]')
    for g, e in effects:
        arrow = "-->|+|" if e == "+" else "-.->|-|"
        lines.append(f"  {adr.replace('-', '_')} {arrow} {g.replace(' ', '_')}")
lines += ["```", "", "## Decision index", "", "| Decision | Title |", "|---|---|"]
for adr in sorted(TITLES):
    lines.append(f"| [{adr}](adr/adr-{adr.split('-')[1]}.md) | {TITLES[adr]} |")
(root / "docs/conflicts.md").write_text("\n".join(lines) + "\n")
print("wrote docs/conflicts.md")
