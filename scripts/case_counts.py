"""Write case counts and the conflict table for the report from the authored case files.

Keeps the report's descriptive numbers (requirements, conflicts, decisions, patterns,
stakeholder roles, metamodel entity types) tied to the files they describe.
"""

import ast
import re
from pathlib import Path

import yaml

root = Path(__file__).resolve().parents[1]
gen = root / "paper/generated"
gen.mkdir(parents=True, exist_ok=True)
case = yaml.safe_load((root / "data/synthetic_case.yaml").read_text())

tree = ast.parse((root / "src/trusttrace/models.py").read_text())
entity_types = [
    n.name
    for n in tree.body
    if isinstance(n, ast.ClassDef) and any(getattr(b, "id", None) == "Entity" for b in n.bases)
]
patterns = re.findall(r"^## P\d+\.", (root / "docs/patterns.md").read_text(), flags=re.M)
must = [r for r in case["requirements"] if r.get("priority") == "must"]

ROLE_NAMES = {
    "shipper": "shipper (an SME exporter)",
    "platform": "platform operator",
    "carrier": "carrier",
    "broker": "customs broker",
    "consignee": "consignee",
    "authority": "competent authority",
    "reviewer": "human document reviewer",
    "provider": "model provider",
}
roles = [ROLE_NAMES.get(s["id"], s["id"]) for s in case["stakeholders"]]
words = {
    7: "seven",
    8: "eight",
    10: "ten",
    15: "fifteen",
    16: "sixteen",
    40: "forty",
}


def macro(name: str, value: object) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


lines = [
    "% generated by scripts/case_counts.py; do not edit",
    macro("NReq", len(case["requirements"])),
    macro("NMust", len(must)),
    macro("NShould", len(case["requirements"]) - len(must)),
    macro("NConflicts", len(case["conflicts"])),
    macro("NConflictsWord", words.get(len(case["conflicts"]), len(case["conflicts"]))),
    macro("NDecisions", len(case["decisions"])),
    macro("NPatterns", len(patterns)),
    macro("NPatternsWord", words.get(len(patterns), len(patterns))),
    macro("NRoles", len(roles)),
    macro("NRolesWord", words.get(len(roles), len(roles))),
    macro("NEntityTypes", len(entity_types)),
    macro("RoleList", ", ".join(roles[:-1]) + " and " + roles[-1]),
]
(gen / "case_counts.tex").write_text("\n".join(lines) + "\n")

rows = [
    r"\begin{table}[t]",
    r"\centering\small",
    r"\caption{Conflicts in the case and resolving decisions (from \texttt{data/synthetic\_case.yaml}).}\label{tab:conflicts}",
    r"\begin{tabularx}{\columnwidth}{@{}lXl@{}}",
    r"\toprule",
    r"ID & Tension & Decision\\",
    r"\midrule",
]
for i, c in enumerate(case["conflicts"], 1):
    desc = c["description"].replace(" versus ", " vs ")
    rows.append(f"C{i} & {desc} & {c['resolution_decision']}\\\\")
rows += [r"\bottomrule", r"\end{tabularx}", r"\end{table}"]
(gen / "conflicts_table.tex").write_text("\n".join(rows) + "\n")
print(
    f"{len(case['requirements'])} requirements, {len(case['conflicts'])} conflicts, "
    f"{len(case['decisions'])} decisions, {len(patterns)} patterns, {len(roles)} roles, "
    f"{len(entity_types)} entity types"
)
